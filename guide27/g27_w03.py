B = lambda s: '<b>' + s + '</b>'
def end(g):
    s = g[g.find('하나님은'):]; assert s.endswith('분이십니다.'), g
    return s[:-len('분이십니다.')] + '분입니다.'
Q = json.load(open(os.path.join(R, '..', 'app', 'site_src', 'guide_qt.json'), encoding='utf8'))['qt']
def keep(n):
    """11-20 새 틀 원고에서 ①②③ 칸을 그대로 가져옴"""
    x = Q[str(n)]; v = x['v27']; g = x['guide']; w = g.get('word', '')
    c = x['obs'].get('christ', ''); ct, _, cb = c.partition(' ')
    return dict(no=n, sub=x.get('sub', ''), today=g['today'], word=list(w.split(' — ', 1)) if w else [],
                scenes=v['scenes'], marks=v['marks'], looks=v['looks'], christ=[ct, cb])
D = []
def day(base, **k):
    d = dict(base); d.update(k)
    d['god'] = [k['god0'], B(k['god1'])]; d['apply'] = dict(lead=k['lead'], fu=[k['fu']])
    d['note'] = k['note'] + ' ' + end(k['god0'])
    for x in ('god0', 'god1', 'lead', 'fu'): d.pop(x)
    D.append(d)

