def endsent(g):
    s = g[g.find('하나님은'):]
    assert s.endswith('분이십니다.'), g
    return s[:-len('분이십니다.')] + '분입니다.'
def rep_field(src, key, field, val):
    i = src.index(f"'{key}': dict(")
    j = src.find("\n'", i + 5); j = len(src) if j < 0 else j
    blk = src[i:j]
    m = re.search(rf"(\n |, ){field}=(['\"]).*?\2(?=,|\))", blk, re.S)
    assert m, (key, field)
    nb = blk[:m.start()] + f"{m.group(1)}{field}={val!r}" + blk[m.end():]
    return src[:i] + nb + src[j:]
