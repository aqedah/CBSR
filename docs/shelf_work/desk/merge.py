multi=('배경','구조')
for fn,items in M.items():
    out=[]
    for kind,v in items:
        if kind=='head': out.append(v); out.append(''); continue
        b=v['name']
        if b=='사도행전': out+=['# 사도행전','']
        if b=='요한계시록': out+=['# 요한계시록','']
        out.append('## %s | %s | %s'%(b,v['id'],v['ch']))
        for k,vals in R[b].items():
            if not vals:
                if k in ('각주','확인','시기'): continue
                raise SystemExit('빈 칸 %s %s'%(b,k))
            if k not in multi and len(vals)!=1: raise SystemExit('여러 줄 %s %s'%(b,k))
            for x in vals: out.append('- %s: %s'%(k,x))
        out.append('')
    open(os.path.join(OUT,fn),'w',encoding='utf-8').write('\n'.join(out).rstrip()+'\n')
