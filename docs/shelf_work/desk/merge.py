def load(d):
    files=collections.OrderedDict()
    for f in sorted(glob.glob(d+'/*.md')):
        items=[]; cur=None
        for ln in open(f,encoding='utf-8').read().split('\n'):
            s=ln.strip()
            m=re.match(r'^## (.+?) \| (\w+) \| (\d+)$',s)
            if m: cur=dict(name=m.group(1),id=m.group(2),ch=m.group(3),f=collections.OrderedDict()); items.append(('book',cur)); continue
            if re.match(r'^# ',s): items.append(('head',s)); cur=None; continue
            m=re.match(r'^- ([^:]+):(?: (.*))?$',s)
            if m and cur is not None: cur['f'].setdefault(m.group(1),[]).append(m.group(2) or '')
        files[os.path.basename(f)]=items
    return files
