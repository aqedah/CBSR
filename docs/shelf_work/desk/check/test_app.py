from playwright.sync_api import sync_playwright
errs=[]; S='/tmp/shelftest/shots/'
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
    cx=b.new_context(viewport={'width':412,'height':699},device_scale_factor=1,has_touch=True,service_workers='block')
    pg=cx.new_page()
    pg.on('pageerror',lambda e: errs.append('PAGEERROR '+str(e)[:200]))
    pg.on('console',lambda m: errs.append('CONSOLE '+m.text[:160]) if m.type=='error' and 'net::' not in m.text and 'Failed to load resource' not in m.text else None)
    pg.goto('http://127.0.0.1:8766/index.html',wait_until='domcontentloaded'); pg.wait_for_timeout(3500)
    print('title',pg.title(),'| rgShelf',pg.locator('#rgShelf').count(),'| hdx buttons',pg.evaluate("[...document.querySelectorAll('#hdx button')].map(b=>b.id+':'+Math.round(b.getBoundingClientRect().left)+'-'+Math.round(b.getBoundingClientRect().right))"))
    print('visible?',pg.locator('#rgShelf').is_visible() if pg.locator('#rgShelf').count() else None, '| tab',pg.evaluate("document.body.dataset.tab"))
    pg.screenshot(path=S+'a1_app.png')
    # 처음 안내나 겹친 창이 있으면 닫기 시도
    top=pg.evaluate("(()=>{const r=document.querySelector('#rgShelf').getBoundingClientRect();const e=document.elementFromPoint(r.left+r.width/2,r.top+r.height/2);return e?(e.id||e.className||e.tagName):''})()")
    print('element at button point:',top)
    pg.evaluate("document.querySelector('#rgShelf').click()"); pg.wait_for_timeout(1800)
    print('shelf open',pg.evaluate("!!document.getElementById('cbsrShelf')"),'| zones',pg.locator('#cbsrShelf .zone').count())
    pg.screenshot(path=S+'a2_app_hall.png')
    pg.click('.zone[data-s="nt"]'); pg.wait_for_timeout(2200); pg.click('.gl button[data-g="일반서신"]'); pg.wait_for_timeout(1300); pg.click('.sp[data-b="jas"]'); pg.wait_for_timeout(2800)
    print('book:',pg.inner_text('#cbsrShelf main h1'),'|',pg.inner_text('#cbsrShelf main dl').replace('\n',' ')[:90])
    pg.click('.nv button[data-a="next"]'); pg.wait_for_timeout(200); print('verse page:',pg.inner_text('#cbsrShelf main').replace('\n',' ')[:110])
    pg.screenshot(path=S+'a3_app_book.png')
    while not pg.locator('#cbsrQa').count(): pg.click('#cbsrShelf .nv button[data-a="next"]'); pg.wait_for_timeout(90)
    pg.fill('#cbsrQa','주님의 형제 야고보가 흩어진 열두 지파에게 썼습니다.'); pg.click('#cbsrShelf .qb .ans'); pg.wait_for_timeout(1500)
    print('앱 기록에 저장:',pg.evaluate("JSON.stringify(JSON.parse(localStorage.getItem('rjnote:y365')||'{}').shq||null)")[:120])
    for i in range(4): pg.go_back(); pg.wait_for_timeout(450)
    print('closed',pg.evaluate("!document.getElementById('cbsrShelf')"),'| app still there',pg.locator('#rgShelf').count(),'| url',pg.url[-30:])
    pg.evaluate("document.querySelector('#rgShelf').click()"); pg.wait_for_timeout(900); pg.click('#cbsrShelf .bk'); pg.wait_for_timeout(500); print('reopen & ‹ 닫기 →',pg.evaluate("!document.getElementById('cbsrShelf')"))
    b.close()
print('errors:',errs[:8])
