from playwright.sync_api import sync_playwright
from PIL import Image
errs = []
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    pg = b.new_page(viewport={'width': 390, 'height': 846})
    pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' else None)
    pg.on('pageerror', lambda e: errs.append('PAGEERROR ' + str(e)))
    pg.goto('file:///home/claude/shelf-desk/dist/index.html')
    pg.wait_for_timeout(500)
    print('rows', pg.locator('.row').count(), '|', pg.inner_text('#count'), '|', pg.inner_text('#save'))
    pg.screenshot(path='check/m1.png')
    pg.click('button.chip[data-g="선지서"]'); print('선지서 rows', pg.locator('.row').count())
    pg.select_option('#st', 'note'); print('각주 rows', [r.inner_text().split('\n')[0] for r in pg.locator('.row').all()])
    pg.select_option('#st', 'all'); pg.click('button.chip[data-g="전체"]')
    pg.click('.row[data-id="zep"]'); pg.wait_for_timeout(200)
    print('hash', pg.evaluate('location.hash'), '| has', pg.evaluate('document.body.className'))
    pg.screenshot(path='check/m2.png')
    pg.fill('#f-when', '요시야 시대, 개혁 이전'); pg.wait_for_timeout(100)
    pg.click('#ok'); pg.wait_for_timeout(100)
    print('after edit:', pg.inner_text('#count'), '| stored', pg.evaluate("localStorage.getItem('cbsr-shelf-desk-v1')")[:120])
    pg.evaluate("document.querySelector('#pv').scrollIntoView()"); pg.wait_for_timeout(100)
    pg.screenshot(path='check/m3.png')
    pg.click('#back'); pg.wait_for_timeout(100)
    print('back → has?', pg.evaluate('document.body.className'), '| zep badges', pg.locator('.row[data-id="zep"]').inner_text().replace('\n', ' '))
    pg.click('#cpy'); pg.wait_for_timeout(200); print('dialog open', pg.evaluate("document.querySelector('#dlg').open"), '|', pg.input_value('#dlga')[:60].replace('\n', ' / '))
    pg.evaluate("document.querySelector('#dlg').close()")
    j = pg.evaluate("(function(){var a=null;try{a=JSON.parse(document.querySelector('#dlga').value)}catch(e){};return a?1:0})()")
    pg.reload(); pg.wait_for_timeout(300); print('after reload:', pg.inner_text('#count'))
    pg.click('.row[data-id="zep"]'); pg.click('#reset'); pg.wait_for_timeout(100); print('after reset:', pg.inner_text('#count'), pg.input_value('#f-when'))
    d = b.new_page(viewport={'width': 1180, 'height': 820}); d.on('pageerror', lambda e: errs.append('PAGEERROR ' + str(e)))
    d.goto('file:///home/claude/shelf-desk/dist/index.html#b-gal'); d.wait_for_timeout(500); d.screenshot(path='check/d1.png')
    b.close()
print('errors:', errs)
ims = [Image.open('check/%s.png' % n) for n in ('m1', 'm2', 'm3')]
sh = Image.new('RGB', (390 * 3 + 40, 866), (60, 60, 60))
for i, im in enumerate(ims): sh.paste(im, (10 + i * 400, 10))
sh.save('check/sheet.png')
